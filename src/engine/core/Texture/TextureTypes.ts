export namespace TextureTypes {
  /**
   * 纹理类型枚举
   */
  export enum TextureType {
    /**
     * 基础颜色贴图
     * 定义物体的基本颜色或反照率，是材质最基础的视觉表现
     */
    BASE_COLOR = 'baseColor',
    
    /**
     * 法线贴图
     * 用于在不增加几何复杂度的情况下模拟表面细节，通过改变表面法线方向来影响光照计算
     * 蓝紫色的图像，储存表面法线XYZ方向信息
     */
    NORMAL = 'normal',
    
    /**
     * 高度贴图
     * 用于视差贴图(Parallax Mapping)或位移贴图(Displacement Mapping)技术
     * 通过灰度值定义表面高度，增强3D深度感和真实感
     */
    HEIGHT = 'height',
    
    /**
     * 凹凸贴图
     * 较传统的表面细节技术，通过灰度图计算法线偏移来模拟表面凹凸
     * 效果不如法线贴图精细，但计算成本较低
     */
    BUMP = 'bump',
    
    /**
     * 粗糙度贴图
     * 控制微表面结构的粗糙程度，影响光线的散射方式
     * 值越高(越白)表面越粗糙，高光越分散；值越低(越黑)表面越光滑，高光越集中
     */
    ROUGHNESS = 'roughness',
    
    /**
     * 金属度贴图
     * 定义表面的金属特性，区分金属和非金属材质
     * 金属(白色)部分使用基础颜色作为镜面反射颜色；非金属(黑色)部分使用固定的反射率
     */
    METALNESS = 'metalness',
    
    /**
     * 环境光遮蔽贴图
     * 模拟物体自阴影和间接光照效果，增加凹陷区域的暗部细节
     * 提高场景深度感和真实感，不受动态光照影响
     */
    AMBIENT_OCCLUSION = 'ambientOcclusion',
    
    /**
     * 自发光贴图
     * 定义物体自身发光的区域和强度，不受外部光照影响
     * 用于霓虹灯、显示屏、灯光等发光效果
     */
    EMISSIVE = 'emissive',
    
    /**
     * 透明度贴图
     * 控制材质的透明度/不透明度
     * 通常为灰度图，黑色表示完全透明，白色表示完全不透明
     */
    ALPHA = 'alpha',
    
    /**
     * 环境贴图
     * 用于环境反射和折射效果，通常为立方体贴图或HDR全景图
     * 提供周围环境的反射信息，增强金属、玻璃等材质的真实感
     */
    ENVIRONMENT = 'environment',
    
    /**
     * 光照贴图
     * 存储预计算的光照信息，用于静态物体的间接光照效果
     * 提高渲染效率，适用于不需要实时光照计算的场景
     */
    LIGHTMAP = 'lightmap',
    
    /**
     * 清漆层贴图
     * 模拟表面上的透明涂层，如汽车漆面、涂漆木材等
     * 控制清漆层的强度和分布
     */
    CLEARCOAT = 'clearcoat',
    
    /**
     * 清漆层粗糙度贴图
     * 控制清漆层的粗糙程度，影响清漆层的反射效果
     * 值越高表面越粗糙，反射越模糊；值越低表面越光滑，反射越清晰
     */
    CLEARCOAT_ROUGHNESS = 'clearcoatRoughness',
    
    /**
     * 清漆层法线贴图
     * 为清漆层提供独立的法线信息，可与基础法线贴图不同
     * 用于模拟表面有细微划痕或纹理的清漆效果
     */
    CLEARCOAT_NORMAL = 'clearcoatNormal',
    
    /**
     * 透射贴图
     * 控制光线通过物体的程度，用于半透明材质如玻璃、塑料等
     * 影响折射效果和内部散射
     */
    TRANSMISSION = 'transmission',
    
    /**
     * 厚度贴图
     * 定义物体在不同区域的厚度，影响次表面散射(Subsurface Scattering)效果
     * 常用于皮肤、蜡、玉石等半透明材质的真实感渲染
     */
    THICKNESS = 'thickness',
    
    /**
     * 光泽贴图
     * 用于模拟布料、绒面革等材质的微光泽效果
     * 在掠射角(接近90度)产生特殊的反射效果
     */
    SHEEN = 'sheen',
    
    /**
     * 高光贴图
     * 控制非金属材质的反射率，可调整不同波长(RGB)的反射强度
     * 用于彩色反射效果，如肥皂泡、某些塑料等材质
     */
    SPECULAR = 'specular',
    
    /**
     * 高光强度贴图
     * 控制高光反射的整体强度，常与高光贴图配合使用
     * 灰度图，值越高反射越强
     */
    SPECULAR_INTENSITY = 'specularIntensity',
    
    /**
     * 各向异性贴图
     * 控制反射在不同方向上的拉伸程度
     * 用于拉丝金属、CD盘、某些布料等材质的特殊反射效果
     */
    ANISOTROPY = 'anisotropy',
    
    /**
     * 各向异性旋转贴图
     * 控制各向异性效果的方向
     * 与各向异性贴图配合使用，精确控制反射的方向性
     */
    ANISOTROPY_ROTATION = 'anisotropyRotation'
  }
} 